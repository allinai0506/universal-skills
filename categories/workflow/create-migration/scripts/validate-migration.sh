#!/bin/bash
# Validate a new Flyway migration file for naming, version, and MySQL compatibility
set -euo pipefail

MIGRATION_FILE="${1:-}"
ROLLBACK_FILE="${2:-}"

if [ -z "$MIGRATION_FILE" ]; then
  echo "Usage: $0 <migration-file> [rollback-file]"
  exit 1
fi

errors=0

# Check naming: V{number}__{description}.sql
BASENAME=$(basename "$MIGRATION_FILE")
if ! echo "$BASENAME" | grep -qE '^V[0-9]+__[A-Za-z0-9_-]+\.sql$'; then
  echo "ERROR: Migration filename '$BASENAME' doesn't match pattern V{number}__{description}.sql"
  errors=$((errors + 1))
fi

# Extract version
VERSION=$(echo "$BASENAME" | sed -n 's/^V\([0-9]*\)__.*/\1/p')

# Check version is numeric
if ! echo "$VERSION" | grep -qE '^[0-9]+$'; then
  echo "ERROR: Could not extract numeric version from '$BASENAME'"
  errors=$((errors + 1))
fi

# Check file is not empty
if [ ! -s "$MIGRATION_FILE" ]; then
  echo "ERROR: Migration file '$MIGRATION_FILE' is empty"
  errors=$((errors + 1))
fi

# Check for MySQL 8.0 compatibility (no H2-specific syntax)
if grep -qi 'GENERATED BY DEFAULT AS IDENTITY' "$MIGRATION_FILE" 2>/dev/null; then
  echo "WARNING: 'GENERATED BY DEFAULT AS IDENTITY' is H2 syntax; use MySQL AUTO_INCREMENT instead"
fi

if grep -qi 'NEXT VALUE FOR' "$MIGRATION_FILE" 2>/dev/null; then
  echo "WARNING: 'NEXT VALUE FOR' is H2 sequence syntax; use MySQL AUTO_INCREMENT instead"
fi

# Check rollback if provided
if [ -n "$ROLLBACK_FILE" ] && [ -f "$ROLLBACK_FILE" ]; then
  RB_BASENAME=$(basename "$ROLLBACK_FILE")
  RB_VERSION=$(echo "$RB_BASENAME" | sed -n 's/^U\([0-9]*\)__.*/\1/p')

  if [ "$RB_VERSION" != "$VERSION" ]; then
    echo "ERROR: Rollback version '$RB_VERSION' doesn't match migration version '$VERSION'"
    errors=$((errors + 1))
  fi
else
  echo "WARNING: No rollback script found (expected: U${VERSION}__*.sql)"
fi

if [ "$errors" -gt 0 ]; then
  echo "FAILED: $errors error(s) found"
  exit 1
else
  echo "OK: Migration validation passed"
fi
